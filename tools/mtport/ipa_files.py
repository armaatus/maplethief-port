"""The per-file hash list of the bundle, for the player import of a repacked IPA (#350).

ADR 0135 (addendum #350): the player import accepts an IPA that is not the exact 1.5 file when
its executable's armv7 slice is 1.5's and every file the game reads matches this list. The list
is made at build time from the user's own extracted copy (``work/ipa/Payload/MapleThief.app``)
and compiled into ``platform/src/ipa_import.cpp`` (``MAPLETHIEF_IPA_FILES``,
``platform/CMakeLists.txt``). It holds paths and SHA-256 hashes only, never a byte of the game,
and is never committed (ADR 0100)::

    PYTHONPATH=tools python3 -m mtport.ipa_files BUNDLE OUT

``scripts/bootstrap`` writes it to ``work/gen/ipa_files.inc`` after the split
(:func:`mtport.bootstrap.split_slices`), so it is wherever ``work/gen`` is: the player builds'
clean clones and the Switch and Linux containers mount ``work/gen`` and nothing else of
``work/``.

Left out (the game never reads them; docs/ANALYSIS.md lists the bundle): the executable, which
the import checks by its armv7 slice; code signing (``_CodeSignature/``, ``CodeResources``,
``ResourceRules.plist``, ``embedded.mobileprovision``, ``SC_Info/``, ``PkgInfo``); the empty
Clutch artifact ``MapleThief_armv6`` and the stray Chartboost ``README.md``. Each line of the
output is a C++ initializer, ``{"<path below the app>", "<sha256>"},``, sorted by path.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

EXECUTABLE = "MapleThief"
# Top-level names below Payload/MapleThief.app/ that the game never reads.
NOT_READ = frozenset(
    {
        EXECUTABLE,
        "_CodeSignature",
        "CodeResources",
        "ResourceRules.plist",
        "embedded.mobileprovision",
        "SC_Info",
        "PkgInfo",
        "MapleThief_armv6",
        "README.md",
    }
)
HEADER = (
    "// Generated by mtport.ipa_files from your own copy of the IPA (ADR 0135, #350): the\n"
    "// SHA-256 of each bundle file the game reads. Hashes only. Never edit; never commit.\n"
)


class IpaFilesError(Exception):
    """The bundle cannot be listed."""


def file_hashes(bundle: Path) -> list[tuple[str, str]]:
    """(path below ``bundle``, SHA-256) of every regular file the game reads, sorted by path."""
    if not bundle.is_dir():
        raise IpaFilesError(f"{bundle} is not a folder (run scripts/bootstrap)")
    out: list[tuple[str, str]] = []
    for p in bundle.rglob("*"):
        rel = p.relative_to(bundle)
        if rel.parts[0] in NOT_READ or p.is_symlink() or not p.is_file():
            continue
        name = rel.as_posix()
        if any(c in name for c in '"\\') or any(ord(c) < 0x20 for c in name):
            raise IpaFilesError(f"{name!r}: a name the list cannot hold")
        out.append((name, hashlib.sha256(p.read_bytes()).hexdigest()))
    if not out:
        raise IpaFilesError(f"{bundle} holds no file the game reads")
    return sorted(out)


def render(hashes: list[tuple[str, str]]) -> str:
    """The include file's text."""
    return HEADER + "".join(f'{{"{name}", "{digest}"}},\n' for name, digest in hashes)


def write(bundle: Path, out: Path) -> int:
    """Write the list of ``bundle`` to ``out`` if it changed (so a build doesn't recompile the
    import for nothing); returns the number of files."""
    hashes = file_hashes(bundle)
    text = render(hashes)
    if not out.is_file() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(f".{out.name}.tmp")
        tmp.write_text(text, encoding="utf-8", newline="\n")
        tmp.replace(out)
    return len(hashes)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python3 -m mtport.ipa_files", description=__doc__.splitlines()[0]
    )
    parser.add_argument("bundle", type=Path, help="work/ipa/Payload/MapleThief.app")
    parser.add_argument("out", type=Path, help="the include file to write")
    args = parser.parse_args(argv)
    try:
        n = write(args.bundle, args.out)
    except IpaFilesError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"ok  {args.out}: {n} file hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
