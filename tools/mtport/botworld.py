"""The play bot's world tables (#297), generated from the compendium's knowledge base.

The chapter runs (``tests/cpp/play_real_test.cpp``, ``tests/cpp/quest_bot.h``) move between
maps over the portals and buy from the town shops. What they need to know about the world
comes from the knowledge base (``mtport.compendium.kb``, ADR 0124), not from hand-written
tables:

* **links**: every portal warp, per chapter: the source map and portal number, the target map,
  and the warp's conditions as a gate (``warp.conditions``: a list of alternatives, each a list
  of terms that hold together). A term on a quest's state (``getQuestState``) or on whether an
  active quest's requirements are met (``checkRequire``: 1 met, 0 not) is one the bot can test
  in guest memory; any other term (the level) is unknown to it, and an alternative with an
  unknown term counts as shut.
* **shops**: every shop an NPC opens (``npc.opens_shop``), per chapter: the map, the NPC's
  object (its script's base name, as the ``.obj`` names it), the shop number and each item it
  sells with its price.

The output is derived from the bundle, so it is written into the build tree at test time
(CTest ``play.bot_world``) and never committed. Format, one record per line, fields separated
by spaces, ``#`` lines are comments::

    link <chapter> <area> <map> <portal> <to_area> <to_map> [<alternative> ...]
    shop <chapter> <area> <map> <object> <shop> <table> <item> <price>

No alternative means the link is always open. An alternative is terms joined by ``&``: a quest
term is ``q<kind>.<number><op><value>`` (``q0.9==2``: main quest 9 is done; ``op`` one of
``== != < <= > >=``), a requirement term is ``r<kind>.<number><op><value>`` (``r1.37==0``: side
quest 37's requirements are not met yet), an unknown term is ``?``. ``table`` is 0 for
equipment and 1 for the other items (the save's ``item_table``).

    python3 -m mtport.botworld --app work/ipa/Payload/MapleThief.app --out FILE [--if-stale]
    python3 -m mtport.botworld --kb build/compendium/kb --out FILE

``--if-stale`` keeps an output newer than every input (the bundle's scripts and maps, this
module and the knowledge base's): building the knowledge base takes a minute or two. Without
the bundle, ``--app`` exits 77 (skipped), as the real-asset tests do.
"""

from __future__ import annotations

import argparse
import dataclasses
import sys
from collections.abc import Container, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

Entities = Mapping[str, Mapping[str, Mapping[str, Any]]]

OPS = ("==", "!=", "<=", ">=", "<", ">")
TABLES = {"equip": 0, "etc": 1}
HEADER = "# MapleThief bot world (#297): generated by mtport.botworld from the knowledge base.\n"


class BotWorldError(Exception):
    """The knowledge base lacks something the tables need."""


@dataclass(frozen=True)
class Term:
    """``getQuestState(kind, number) <op> value``, or with ``require`` ``checkRequire(kind,
    number) <op> value``; ``quest`` None is a term the bot can't test."""

    quest: tuple[int, int] | None
    op: str = "=="
    value: int = 0
    require: bool = False

    def text(self) -> str:
        if self.quest is None:
            return "?"
        return f"{'r' if self.require else 'q'}{self.quest[0]}.{self.quest[1]}{self.op}{self.value}"


UNKNOWN = Term(None)


@dataclass(frozen=True)
class Link:
    chapter: int
    area: int
    map: int
    portal: int
    to_area: int
    to_map: int
    gate: tuple[tuple[Term, ...], ...] = ()  # () = always open

    def line(self) -> str:
        alts = " ".join("&".join(t.text() for t in alt) for alt in self.gate)
        head = (
            f"link {self.chapter} {self.area} {self.map} {self.portal} {self.to_area} {self.to_map}"
        )
        return f"{head} {alts}" if alts else head


@dataclass(frozen=True, order=True)
class Shop:
    chapter: int
    area: int
    map: int
    npc: str  # the NPC object's name (its script's base name)
    shop: int
    table: int  # 0 equipment, 1 other items
    item: int
    price: int

    def line(self) -> str:
        return (
            f"shop {self.chapter} {self.area} {self.map} {self.npc} {self.shop} {self.table} "
            f"{self.item} {self.price}"
        )


def map_numbers(map_id: str) -> tuple[int, int]:
    """``"10-3"`` -> ``(10, 3)``."""
    area, _, number = map_id.partition("-")
    return int(area), int(number)


def item_ref(item_id: str) -> tuple[int, int]:
    """``"etc:3"`` -> ``(1, 3)``."""
    table, _, number = item_id.partition(":")
    if table not in TABLES:
        raise BotWorldError(f"item {item_id!r}: unknown table")
    return TABLES[table], int(number)


def term(cond: Mapping[str, Any]) -> Term:
    native, quest, args = cond.get("native"), cond.get("quest"), cond.get("args")
    if cond.get("op") not in OPS:
        return UNKNOWN
    if native == "getQuestState" and quest is not None:
        return Term((int(quest[0]), int(quest[1])), cond["op"], int(cond["value"]))
    if native == "checkRequire" and isinstance(args, list) and len(args) == 2:
        return Term((int(args[0]), int(args[1])), cond["op"], int(cond["value"]), require=True)
    return UNKNOWN


def gate(conditions: Sequence[Sequence[Mapping[str, Any]]]) -> tuple[tuple[Term, ...], ...]:
    """A warp's conditions as a gate: ``[[]]`` (always) is ``()``; ``[]`` (never) one unknown."""
    if any(len(alt) == 0 for alt in conditions):
        return ()
    if not conditions:
        return ((UNKNOWN,),)
    return tuple(tuple(term(c) for c in alt) for alt in conditions)


def links(entities: Entities) -> list[Link]:
    """Every portal warp the game runs, once per chapter it runs in, sorted."""
    out: set[Link] = set()
    for warp in entities.get("warp", {}).values():
        if not warp.get("used"):
            continue
        to_area, to_map = map_numbers(warp["target_map"])
        g = gate(warp["conditions"])
        for src in warp["from"]:
            if src["role"] != "portal" or src["portal"] is None:
                continue
            area, number = map_numbers(src["map"])
            for chapter in warp["chapters"]:
                out.add(Link(chapter, area, number, src["portal"], to_area, to_map, g))
    return sorted(out, key=lambda lk: (*dataclasses.astuple(lk)[:6], lk.line()))


def _object_name(entities: Entities, script_id: str) -> str:
    script = entities.get("script", {}).get(script_id)
    if script is not None and script.get("base_name"):
        return str(script["base_name"])
    return script_id.split("-", 1)[-1]


def shops(entities: Entities) -> list[Shop]:
    """Every item of every shop an NPC opens, per chapter and map where it does, sorted."""
    out: set[Shop] = set()
    for shop in entities.get("shop", {}).values():
        for opener in shop.get("opened_by", []):
            area, number = map_numbers(opener["map"])
            npc = _object_name(entities, opener["script"])
            if not npc or any(c.isspace() for c in npc):
                raise BotWorldError(f"shop {shop['id']}: object name {npc!r}")
            for chapter in opener.get("chapters", []):
                for sold in shop.get("sells", []):
                    table, item = item_ref(sold["id"])
                    out.add(
                        Shop(
                            chapter,
                            area,
                            number,
                            npc,
                            int(shop["id"]),
                            table,
                            item,
                            int(sold["price"]),
                        )
                    )
    return sorted(out)


def render(link_list: Sequence[Link], shop_list: Sequence[Shop]) -> str:
    lines = [HEADER.rstrip("\n")]
    lines += [lk.line() for lk in link_list]
    lines += [s.line() for s in shop_list]
    return "\n".join(lines) + "\n"


def generate(entities: Entities) -> str:
    link_list = links(entities)
    if not link_list:
        raise BotWorldError("the knowledge base has no portal warps")
    return render(link_list, shops(entities))


def _parse_term(text: str) -> Term:
    if text == "?":
        return UNKNOWN
    if text[:1] not in ("q", "r"):
        raise BotWorldError(f"term {text!r}")
    for op in OPS:
        left, sep, right = text[1:].partition(op)
        if sep:
            kind, _, number = left.partition(".")
            return Term((int(kind), int(number)), op, int(right), require=text[0] == "r")
    raise BotWorldError(f"term {text!r}: no operator")


def parse(text: str) -> tuple[list[Link], list[Shop]]:
    """Read the tables back (the C++ reader in tests/cpp/world_map.h does the same)."""
    link_list: list[Link] = []
    shop_list: list[Shop] = []
    for n, line in enumerate(text.splitlines(), 1):
        f = line.split()
        if not f or f[0].startswith("#"):
            continue
        try:
            if f[0] == "link" and len(f) >= 7:
                g = tuple(tuple(_parse_term(t) for t in alt.split("&")) for alt in f[7:])
                link_list.append(Link(*(int(x) for x in f[1:7]), gate=g))
            elif f[0] == "shop" and len(f) == 9:
                nums = [int(x) for x in f[1:4]] + [f[4]] + [int(x) for x in f[5:9]]
                shop_list.append(Shop(*nums))  # type: ignore[arg-type]
            else:
                raise BotWorldError("not a record")
        except (ValueError, BotWorldError) as e:
            raise BotWorldError(f"line {n}: {line!r}: {e}") from e
    return link_list, shop_list


def open_now(
    link: Link,
    quest_state: Mapping[tuple[int, int], int],
    met: Container[tuple[int, int]] = (),
) -> bool:
    """Whether the bot may take ``link`` with these quest states (missing: 0, not started) and
    the active quests whose requirements are ``met``."""
    if not link.gate:
        return True

    def holds(t: Term) -> bool:
        if t.quest is None:
            return False
        v = int(t.quest in met) if t.require else quest_state.get(t.quest, 0)
        return {
            "==": v == t.value,
            "!=": v != t.value,
            "<": v < t.value,
            "<=": v <= t.value,
            ">": v > t.value,
            ">=": v >= t.value,
        }[t.op]

    return any(all(holds(t) for t in alt) for alt in link.gate)


SKIPPED = 77


def _newest(paths: Sequence[Path]) -> float:
    newest = 0.0
    for p in paths:
        if p.is_dir():
            for f in p.rglob("*"):
                newest = max(newest, f.stat().st_mtime)
        elif p.exists():
            newest = max(newest, p.stat().st_mtime)
    return newest


def stale(out: Path, app: Path) -> bool:
    """Whether ``out`` is missing or older than an input of ``--app``."""
    if not out.is_file():
        return True
    here = Path(__file__).resolve().parent
    inputs = [app / "script", app / "map", Path(__file__).resolve(), here / "compendium"]
    return out.stat().st_mtime < _newest(inputs)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python3 -m mtport.botworld", description=__doc__.splitlines()[0]
    )
    src = parser.add_mutually_exclusive_group(required=True)
    src.add_argument("--app", type=Path, help="the extracted MapleThief.app (builds the KB)")
    src.add_argument("--kb", type=Path, help="a knowledge base built by mtport.compendium.kb")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--if-stale", action="store_true", help="keep an up-to-date output")
    args = parser.parse_args(argv)
    from mtport.compendium import kb

    try:
        if args.kb is not None:
            entities: Entities = kb.load_kb(args.kb)
        else:
            if not (args.app / "map").is_dir():
                print(f"skipped: {args.app}: no extracted bundle (run scripts/bootstrap)")
                return SKIPPED
            if args.if_stale and not stale(args.out, args.app):
                print(f"{args.out} is up to date")
                return 0
            entities = kb.build(args.app).entities
        text = generate(entities)
    except (OSError, kb.KBError, BotWorldError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_name(args.out.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(args.out)
    link_list, shop_list = parse(text)
    print(f"wrote {args.out}: {len(link_list)} links, {len(shop_list)} shop items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
