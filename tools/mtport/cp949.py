"""The CP949 (EUC-KR / Unified Hangul Code) table of the runtime's CFString encodings (#48).

The game converts every table string with ``kCFStringEncodingEUC_KR`` (docs/ANALYSIS.md), so
the runtime (``runtime/src/cf/encoding.cpp``, ADR 0032) decodes and encodes CP949 itself, the
same on every host. It needs one table: the KS X 1001 region (lead and trail bytes
0xA1-0xFE, 94 x 94 codes), generated here from Python's ``cp949`` codec into
``runtime/src/cf/cp949_table.inc``. That is Unicode mapping data, nothing from the game.

The rest of CP949 is computed, not tabled: its extension codes (lead 0x81-0xC6, trail
0x41-0x5A, 0x61-0x7A, 0x81-0xFE, the latter only up to 0xA0 for leads from 0xA1) are the
8,822 Hangul syllables that KS X 1001 lacks, in Unicode order. :func:`check_extension`
proves that rule against the codec; the generator refuses to write a table if it fails.

CLI::

    python3 -m mtport.cp949 write [OUT]   writes the table (default: the runtime's file)
    python3 -m mtport.cp949 check [OUT]   exit 1 if the file differs from what write writes
"""

from __future__ import annotations

import sys
from pathlib import Path

ROWS = 94
FIRST = 0xA1
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3
TABLE = Path(__file__).resolve().parents[2] / "runtime" / "src" / "cf" / "cp949_table.inc"


def decode_pair(lead: int, trail: int) -> int:
    """The code point of a two-byte CP949 code, or 0 if the codec has none."""
    try:
        text = bytes((lead, trail)).decode("cp949")
    except UnicodeDecodeError:
        return 0
    return ord(text) if len(text) == 1 else 0


def ksx1001() -> list[int]:
    """The KS X 1001 region, row-major: entry (lead - 0xA1) * 94 + (trail - 0xA1)."""
    return [decode_pair(FIRST + i // ROWS, FIRST + i % ROWS) for i in range(ROWS * ROWS)]


def extension_trails(lead: int) -> list[int]:
    """The trail bytes of the extension codes under ``lead``."""
    high_end = 0xFF if lead <= 0xA0 else 0xA1
    return [*range(0x41, 0x5B), *range(0x61, 0x7B), *range(0x81, high_end)]


def extension(table: list[int]) -> dict[tuple[int, int], int]:
    """The extension codes by the rule in the module docstring."""
    present = set(table)
    missing = [c for c in range(HANGUL_FIRST, HANGUL_LAST + 1) if c not in present]
    codes = [(lead, t) for lead in range(0x81, 0xC7) for t in extension_trails(lead)]
    return dict(zip(codes, missing))


def check_extension(table: list[int]) -> None:
    """Raises ValueError unless the rule gives exactly the codec's two-byte codes outside
    the KS X 1001 region."""
    computed = extension(table)
    codec = {}
    for lead in range(0x81, 0xFF):
        for trail in range(0x41, 0xFF):
            if lead >= FIRST and trail >= FIRST:
                continue
            cp = decode_pair(lead, trail)
            if cp:
                codec[(lead, trail)] = cp
    if computed != codec:
        raise ValueError(f"CP949 extension rule: {len(computed)} computed, {len(codec)} in codec")


def render(table: list[int]) -> str:
    lines = [
        "// Generated by tools/mtport/cp949.py (python3 -m mtport.cp949 write); do not edit.",
        "// KS X 1001 (the EUC-KR region of CP949): code point of (lead, trail), both 0xA1-0xFE,",
        "// at (lead - 0xA1) * 94 + (trail - 0xA1); 0 = no character. From Python's cp949 codec.",
        "// clang-format off",
    ]
    for start in range(0, len(table), 12):
        lines.append(" ".join(f"0x{v:04X}," for v in table[start : start + 12]))
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def generate() -> str:
    table = ksx1001()
    check_extension(table)
    return render(table)


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in ("write", "check"):
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(argv[1]) if len(argv) > 1 else TABLE
    text = generate()
    if argv[0] == "write":
        out.write_text(text, encoding="utf-8", newline="\n")
        return 0
    current = out.read_text(encoding="utf-8") if out.exists() else ""
    if current != text:
        print(f"{out} is stale: run python3 -m mtport.cp949 write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
