"""Release helpers (ADR 0024, ADR 0125): the content guard for the release downloads, tags,
and checksum files.

A release carries, per platform, one *port kit* built from our own code only and one *player
build*: the game executable linked with the recompiled code, with none of the game's assets
(ADR 0100, ADR 0125). The **content guard** opens a package (``.zip``, ``.tar.gz`` or an
unpacked directory) and fails if any file in it could be something it must not carry. It has
two modes (``--mode``, default ``kit``):

* ``kit``: every rule below;
* ``player``: the same rules, except that binaries may hold the recompiled code (the
  ``f_XXXXXXXX`` symbols and the dispatch table); instead at least one binary must hold it,
  so a placeholder shell is never released as the game.

The rules:

* **paths**: a member under ``work/``, ``assets-out/`` or ``build/``, a CMake build-tree
  output (``CMakeFiles/``, ``_deps/``, ``CMakeCache.txt``, ...), anything inside an IPA's
  ``Payload/<name>.app/`` folder (the game's bundle, its executable ``MapleThief`` included),
  an ``*.ipa``, or a nested archive the guard can't look into; an unsafe member name
  (absolute, ``..``) or a link that points outside the kit;
* **generated code**: the recompiler's file names (``mt_gen.h``, ``fn_NNN.c``,
  ``dispatch.c``, ``imports.c``, ``gen.cmake``; recomp/output.py), and C/C++ sources that
  include ``mt_gen.h`` or carry the recompiler's ``Generated by recomp`` banner;
* **derived bytes**: a non-empty file whose SHA-256 equals a file of a reference directory:
  by default ``work/ipa/`` (the extracted IPA), ``work/gen/`` and ``assets-out/``, those that
  exist (CI has none of them; the release machines have them); any image or audio file,
  since the packages carry none of our own (a re-encoded game image would escape the hash),
  except the port's own icon files of :data:`ICON_ALLOWLIST`, by path and SHA-256; and a
  32-bit ARM Mach-O, which only the iOS game's executable is;
* **recompiled code in binaries** (kit mode only; Mach-O, ELF, PE/COFF, ``ar`` archives, or
  any file with a NUL byte): the symbols only generated code defines (``f_XXXXXXXX`` guest
  functions, recomp/lift/core.py; ``mt_import_thunk_N``, recomp/imports.py; ``mt_fn_first``,
  recomp/dispatch.py) and, when ``work/gen/dispatch.c`` exists, the first entries of the
  dispatch table ``mt_fn_table`` as data (guest addresses, little-endian, 8 or 16 bytes
  apart), which a stripped executable keeps too. The runtime only *references* the
  dispatch and import tables (``mt_fn_table``, ``mt_import_table``), so those names are
  allowed;
* **the guest symbol table** (``# maplethief symbols`` text, recomp/symbols.py, ADR 0030):
  function names of the game, whatever the file is called.

The kit is untrusted input: members are read into memory, never extracted or executed, and
links are not followed.

CLI::

    python3 -m mtport.release guard KIT... [--mode kit|player] [--reference DIR]...
                                           [--no-default-references]
    python3 -m mtport.release tag vX.Y.Z[-rc.N]         prints the version and release|prerelease
    python3 -m mtport.release kits VERSION              the expected kit file names, one a line
    python3 -m mtport.release players VERSION           the expected player build file names
    python3 -m mtport.release sha256 FILE...            writes FILE.sha256 next to each FILE
    python3 -m mtport.release sums OUT FILE.sha256...   merges them into OUT (SHA256SUMS)
    python3 -m mtport.release check SUMS                checks the files next to SUMS

Checksum files use the ``sha256sum``/``shasum -a 256`` format, ``<hex>  <name>``, so
``sha256sum -c`` and ``shasum -a 256 -c`` read them.
"""

