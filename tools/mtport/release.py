"""Release helpers (ADR 0024): the content guard for the port kits, tags, and checksum files.

A release carries one *port kit* per platform, built from our own code only. The **content
guard** opens a kit (``.zip``, ``.tar.gz`` or an unpacked directory) and fails if any file in
it could be the game build or something derived from the IPA:

* **paths**: a member under ``work/``, ``assets-out/`` or ``build/``, a CMake build-tree
  output (``CMakeFiles/``, ``_deps/``, ``CMakeCache.txt``, ...), an ``*.ipa``, or a nested
  archive the guard can't look into; an unsafe member name (absolute, ``..``) or a link that
  points outside the kit;
* **generated code**: the recompiler's file names (``mt_gen.h``, ``fn_NNN.c``,
  ``dispatch.c``, ``imports.c``, ``gen.cmake``; recomp/output.py), and C/C++ sources that
  include ``mt_gen.h`` or carry the recompiler's ``Generated by recomp`` banner;
* **derived bytes**: a non-empty file whose SHA-256 equals a file of a reference directory:
  by default ``work/ipa/`` (the extracted IPA), ``work/gen/`` and ``assets-out/``, those that
  exist (CI has none of them; the release machines have them);
* **recompiled code in binaries** (Mach-O, ELF, PE/COFF, ``ar`` archives, or any file with a
  NUL byte): the symbols only generated code defines (``f_XXXXXXXX`` guest functions,
  recomp/lift/core.py; ``mt_import_thunk_N``, recomp/imports.py; ``mt_fn_first``,
  recomp/dispatch.py) and, when ``work/gen/dispatch.c`` exists, the first entries of the
  dispatch table ``mt_fn_table`` as data (guest addresses, little-endian, 8 or 16 bytes
  apart), which a stripped executable keeps too. The runtime only *references* the
  dispatch and import tables (``mt_fn_table``, ``mt_import_table``), so those names are
  allowed.

The kit is untrusted input: members are read into memory, never extracted or executed, and
links are not followed.

CLI::

    python3 -m mtport.release guard KIT... [--reference DIR]... [--no-default-references]
    python3 -m mtport.release tag vX.Y.Z[-rc.N]         prints the version and release|prerelease
    python3 -m mtport.release kits VERSION              the expected kit file names, one a line
    python3 -m mtport.release sha256 FILE...            writes FILE.sha256 next to each FILE
    python3 -m mtport.release sums OUT FILE.sha256...   merges them into OUT (SHA256SUMS)
    python3 -m mtport.release check SUMS                checks the files next to SUMS

Checksum files use the ``sha256sum``/``shasum -a 256`` format, ``<hex>  <name>``, so
``sha256sum -c`` and ``shasum -a 256 -c`` read them.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import stat
import sys
import tarfile
import zipfile
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[2]
# The directories derived from the IPA (CLAUDE.md "What goes in git"), checked by hash.
DEFAULT_REFERENCES = ("work/ipa", "work/gen", "assets-out")
GEN_DISPATCH = "work/gen/dispatch.c"

# vX.Y.Z or vX.Y.Z-rc.N (ADR 0024); the version is the tag without its "v".
TAG = re.compile(r"v(?P<version>(?P<numeric>\d+\.\d+\.\d+)(?P<rc>-rc\.\d+)?)")
# Kit file names per platform (cmake/Packaging.cmake), in the order a release lists them.
KIT_PLATFORMS = (
    ("macos-universal", "zip"),
    ("linux-x86_64", "tar.gz"),
    ("windows-x64", "zip"),
)

FORBIDDEN_DIRS = {"work", "assets-out", "build", "CMakeFiles", "_deps", "Testing"}
BUILD_TREE_FILES = {
    "CMakeCache.txt",
    "build.ninja",
    ".ninja_log",
    ".ninja_deps",
    "cmake_install.cmake",
    "CTestTestfile.cmake",
    "compile_commands.json",
    "install_manifest.txt",
}
GENERATED_NAMES = {"mt_gen.h", "dispatch.c", "imports.c", "gen.cmake"}
GENERATED_UNIT = re.compile(r"fn_\d{3}\.c")
C_SUFFIXES = {".c", ".h", ".cc", ".cpp", ".hpp", ".inc"}
GENERATED_MARKERS = (b'#include "mt_gen.h"', b"Generated by recomp")
ARCHIVE_SUFFIXES = (".ipa", ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".dmg")

# Symbols that only the generated code defines. The lookarounds keep them from matching
# inside longer identifiers; Mach-O prefixes C names with "_", which is allowed before them.
GENERATED_SYMBOL = re.compile(
    rb"(?<![A-Za-z0-9])(?:f_[0-9A-F]{8}|mt_import_thunk_[0-9]+|mt_fn_first)(?![A-Za-z0-9_])"
)
BINARY_MAGICS = (
    b"\xfe\xed\xfa\xce",  # Mach-O 32-bit, big-endian
    b"\xce\xfa\xed\xfe",  # Mach-O 32-bit
    b"\xfe\xed\xfa\xcf",  # Mach-O 64-bit, big-endian
    b"\xcf\xfa\xed\xfe",  # Mach-O 64-bit
    b"\xca\xfe\xba\xbe",  # fat Mach-O
    b"\x7fELF",
    b"MZ",  # PE
    b"!<arch>\n",  # ar archive (.a, MSVC .lib)
)
# How many leading mt_fn_table entries make a match; 8 guest addresses in a row, at a fixed
# stride, don't happen by chance.
TABLE_RUN = 8
TABLE_ENTRY = re.compile(r"\{0x([0-9A-Fa-f]{8})u, f_[0-9A-Fa-f]{8}\}")
MAX_MEMBER = 2 << 30  # GitHub's limit per release asset


class GuardError(Exception):
    """The kit can't be read at all (not a zip/tar.gz/directory, or corrupt)."""


@dataclass(frozen=True)
class Member:
    """One entry of a kit: its path inside the kit, its kind, and a file's bytes."""

    name: str
    kind: str  # "file", "dir", "symlink", "hardlink" or "other"
    data: bytes = b""
    target: str = ""  # a link's target


@dataclass(frozen=True)
class Finding:
    member: str
    rule: str  # "path", "generated", "derived" or "symbols"
    detail: str

    def __str__(self) -> str:
        return f"{self.member}: [{self.rule}] {self.detail}"


@dataclass
class Report:
    kit: str
    files: int = 0
    size: int = 0
    findings: list[Finding] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.findings


# --- Reading kits --------------------------------------------------------------------------


def _read_capped(stream, name: str) -> bytes:
    data = stream.read(MAX_MEMBER + 1)
    if len(data) > MAX_MEMBER:
        raise GuardError(f"{name}: member larger than {MAX_MEMBER} bytes")
    return data


def _zip_members(path: Path) -> Iterator[Member]:
    try:
        archive = zipfile.ZipFile(path)
    except zipfile.BadZipFile as e:
        raise GuardError(f"{path}: not a zip file: {e}") from e
    with archive:
        for info in archive.infolist():
            mode = info.external_attr >> 16
            if info.is_dir():
                yield Member(info.filename, "dir")
            elif stat.S_ISLNK(mode):
                target = archive.read(info).decode("utf-8", "replace")
                yield Member(info.filename, "symlink", target=target)
            else:
                with archive.open(info) as f:
                    yield Member(info.filename, "file", _read_capped(f, info.filename))


def _tar_members(path: Path) -> Iterator[Member]:
    try:
        archive = tarfile.open(path, "r:*")
    except tarfile.TarError as e:
        raise GuardError(f"{path}: not a tar file: {e}") from e
    with archive:
        for info in archive:
            if info.isdir():
                yield Member(info.name, "dir")
            elif info.issym():
                yield Member(info.name, "symlink", target=info.linkname)
            elif info.islnk():
                yield Member(info.name, "hardlink", target=info.linkname)
            elif info.isreg():
                f = archive.extractfile(info)
                yield Member(info.name, "file", _read_capped(f, info.name) if f else b"")
            else:
                yield Member(info.name, "other")


def _dir_members(path: Path) -> Iterator[Member]:
    for p in sorted(path.rglob("*")):
        name = p.relative_to(path).as_posix()
        if p.is_symlink():
            yield Member(name, "symlink", target=str(p.readlink()))
        elif p.is_dir():
            yield Member(name, "dir")
        elif p.is_file():
            yield Member(name, "file", p.read_bytes())
        else:
            yield Member(name, "other")


def members(path: Path) -> Iterator[Member]:
    """The entries of a kit: a directory, a ``.zip`` or a tar archive (``.tar.gz``)."""
    if path.is_dir():
        return _dir_members(path)
    if not path.is_file():
        raise GuardError(f"{path}: no such file")
    if zipfile.is_zipfile(path):
        return _zip_members(path)
    if tarfile.is_tarfile(path):
        return _tar_members(path)
    raise GuardError(f"{path}: neither a zip nor a tar archive")


# --- References ----------------------------------------------------------------------------


def reference_hashes(dirs: Iterable[Path]) -> dict[str, str]:
    """SHA-256 -> a path, for every non-empty regular file below ``dirs`` (missing ones are
    skipped). Empty files carry nothing and would match every empty file of a kit."""
    hashes: dict[str, str] = {}
    for d in dirs:
        if not d.is_dir():
            continue
        for p in sorted(d.rglob("*")):
            if p.is_file() and not p.is_symlink() and p.stat().st_size > 0:
                hashes.setdefault(hashlib.sha256(p.read_bytes()).hexdigest(), str(p))
    return hashes


def dispatch_table_addresses(dispatch_c: Path) -> list[int]:
    """The first :data:`TABLE_RUN` guest addresses of ``mt_fn_table`` in a generated
    ``dispatch.c`` (recomp/dispatch.py), or [] if it is absent or has fewer entries."""
    if not dispatch_c.is_file():
        return []
    text = dispatch_c.read_text(encoding="utf-8", errors="replace")
    start = text.find("mt_fn_table[]")
    if start < 0:
        return []
    found = []
    for m in TABLE_ENTRY.finditer(text, start):
        found.append(int(m.group(1), 16))
        if len(found) == TABLE_RUN:
            return found
    return []


def find_table(data: bytes, addresses: list[int]) -> int:
    """Offset of ``addresses`` stored as consecutive little-endian u32 table keys, 8 or 16
    bytes apart (32- or 64-bit hosts' ``mt_fn_entry``), or -1."""
    if not addresses:
        return -1
    keys = [a.to_bytes(4, "little") for a in addresses]
    pos = data.find(keys[0])
    while pos >= 0:
        for stride in (8, 16):
            if all(
                data[pos + i * stride : pos + i * stride + 4] == key
                for i, key in enumerate(keys[1:], 1)
            ):
                return pos
        pos = data.find(keys[0], pos + 1)
    return -1


# --- The guard -----------------------------------------------------------------------------


def is_binary(data: bytes) -> bool:
    return data.startswith(BINARY_MAGICS) or b"\0" in data[:8192]


def _unsafe(name: str) -> bool:
    if name.startswith(("/", "\\")) or re.match(r"[A-Za-z]:", name):
        return True
    return ".." in re.split(r"[/\\]", name)


def _link_escapes(member: Member, top: str) -> bool:
    """True if a link's target lies outside the kit (below ``top``, the kit's top-level
    directory, if it has one). A symbolic link's target is relative to its directory, a tar
    hard link's to the archive root."""
    target = member.target.replace("\\", "/")
    if not target or target.startswith("/") or re.match(r"[A-Za-z]:", target):
        return True
    parts = PurePosixPath(target).parts
    if member.kind == "hardlink":
        return ".." in parts or bool(top) and parts[0] != top
    # Directories between the kit's root and the link.
    depth = len(PurePosixPath(member.name).parts) - 1 - (1 if top else 0)
    for part in parts:
        if part == "..":
            depth -= 1
            if depth < 0:
                return True
        elif part != ".":
            depth += 1
    return False


def check_member(
    member: Member, refs: dict[str, str], table: list[int], top_level: bool = True
) -> list[Finding]:
    """Every rule ``member`` breaks. ``top_level``: the kit's first path component is its own
    directory (MapleThief-kit-...), so the path rules look below it."""
    name = member.name.rstrip("/")
    out: list[Finding] = []

    def found(rule: str, detail: str) -> None:
        out.append(Finding(name, rule, detail))

    if _unsafe(name):
        found("path", "unsafe member name (absolute or '..')")
        return out
    parts = PurePosixPath(name).parts
    top = parts[0] if top_level and len(parts) > 1 else ""
    inner = parts[1:] if top else parts
    base = parts[-1] if parts else ""
    for part in inner[:-1] if member.kind != "dir" else inner:
        if part in FORBIDDEN_DIRS:
            found("path", f"inside a '{part}/' directory (work/, assets-out/ or build output)")
            break
    if member.kind == "dir":
        return out
    if base in BUILD_TREE_FILES:
        found("path", "a CMake build-tree file")
    if base.lower().endswith(ARCHIVE_SUFFIXES):
        found("path", "an IPA or nested archive (the guard can't look inside)")
    if member.kind in ("symlink", "hardlink"):
        if _link_escapes(member, top):
            found("path", f"{member.kind} to '{member.target}' points outside the kit")
        return out
    if member.kind != "file":
        found("path", "not a regular file, directory or link")
        return out

    if base in GENERATED_NAMES or GENERATED_UNIT.fullmatch(base):
        found("generated", "a file name the recompiler writes into work/gen/")
    data = member.data
    if PurePosixPath(base).suffix.lower() in C_SUFFIXES:
        for marker in GENERATED_MARKERS:
            if marker in data:
                found("generated", f"C/C++ source containing {marker.decode()!r}")
                break
    if data:
        digest = hashlib.sha256(data).hexdigest()
        if digest in refs:
            found("derived", f"same SHA-256 as {refs[digest]}")
    if is_binary(data):
        symbols = sorted({m.group(0).decode() for m in GENERATED_SYMBOL.finditer(data)})
        if symbols:
            shown = ", ".join(symbols[:5]) + (", ..." if len(symbols) > 5 else "")
            found("symbols", f"binary with {len(symbols)} generated-code symbol(s): {shown}")
        offset = find_table(data, table)
        if offset >= 0:
            found("symbols", f"binary holding the dispatch table (mt_fn_table) at 0x{offset:X}")
    return out


def guard(kit: Path, refs: dict[str, str], table: list[int]) -> Report:
    """Run every rule over ``kit``. Raises :class:`GuardError` if it can't be read."""
    report = Report(str(kit))
    entries = list(members(kit))
    tops = {PurePosixPath(m.name).parts[0] for m in entries if m.name.strip("/")}
    # An archive made by CPack (or ditto --keepParent) has one top-level directory.
    top_level = not kit.is_dir() and len(tops) == 1
    for m in entries:
        if m.kind == "file":
            report.files += 1
            report.size += len(m.data)
        report.findings += check_member(m, refs, table, top_level)
    return report


# --- Tags, kit names, checksums ------------------------------------------------------------


def parse_tag(tag: str) -> tuple[str, bool]:
    """``vX.Y.Z[-rc.N]`` -> (version, is_prerelease). Raises ValueError otherwise."""
    m = TAG.fullmatch(tag)
    if not m:
        raise ValueError(f"tag '{tag}' is not vX.Y.Z or vX.Y.Z-rc.N")
    return m.group("version"), m.group("rc") is not None


def kit_names(version: str) -> list[str]:
    """The kit file names of a release, one per platform (cmake/Packaging.cmake)."""
    return [f"MapleThief-kit-{version}-{plat}.{ext}" for plat, ext in KIT_PLATFORMS]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


SUM_LINE = re.compile(r"([0-9a-f]{64}) [ *](\S(?:.*\S)?)")


def sum_line(digest: str, name: str) -> str:
    return f"{digest}  {name}\n"


def write_sha256(path: Path) -> Path:
    """Write ``<path>.sha256``: one ``<hex>  <file name>`` line, LF-terminated."""
    out = path.with_name(path.name + ".sha256")
    out.write_bytes(sum_line(sha256_file(path), path.name).encode("utf-8"))
    return out


def parse_sums(text: str, source: str = "<sums>") -> dict[str, str]:
    """name -> hex digest from checksum lines. Raises ValueError on a malformed or duplicate
    line, or a name with a path in it."""
    sums: dict[str, str] = {}
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        m = SUM_LINE.fullmatch(line)
        if not m:
            raise ValueError(f"{source}:{n}: not '<sha256>  <name>': {line!r}")
        digest, name = m.groups()
        if "/" in name or "\\" in name:
            raise ValueError(f"{source}:{n}: '{name}' is a path, not a file name")
        if name in sums:
            raise ValueError(f"{source}:{n}: '{name}' listed twice")
        sums[name] = digest
    return sums


def merge_sums(files: Iterable[Path]) -> str:
    """The SHA256SUMS text of the ``.sha256`` files, sorted by name."""
    merged: dict[str, str] = {}
    for f in files:
        for name, digest in parse_sums(f.read_text(encoding="utf-8"), str(f)).items():
            if name in merged and merged[name] != digest:
                raise ValueError(f"{f}: '{name}' has two different checksums")
            merged[name] = digest
    return "".join(sum_line(merged[n], n) for n in sorted(merged))


def check_sums(sums_path: Path) -> list[str]:
    """Check every file listed in ``sums_path`` against the file next to it, like
    ``sha256sum -c``. Returns the failures (empty when all match)."""
    sums = parse_sums(sums_path.read_text(encoding="utf-8"), str(sums_path))
    failures = []
    for name, digest in sums.items():
        f = sums_path.parent / name
        if not f.is_file():
            failures.append(f"{name}: missing")
        elif sha256_file(f) != digest:
            failures.append(f"{name}: FAILED")
        else:
            print(f"{name}: OK")
    return failures


# --- CLI -----------------------------------------------------------------------------------


def _cmd_guard(args: argparse.Namespace) -> int:
    dirs = [Path(d) for d in args.reference]
    if not args.no_default_references:
        dirs += [REPO / d for d in DEFAULT_REFERENCES]
    present = [d for d in dirs if d.is_dir()]
    refs = reference_hashes(present)
    table = dispatch_table_addresses(Path(args.dispatch) if args.dispatch else REPO / GEN_DISPATCH)
    print(
        f"guard: {len(refs)} reference hashes from "
        f"{', '.join(str(d) for d in present) or 'no reference directory (none present)'}; "
        f"dispatch-table check {'on' if table else 'off (no work/gen/dispatch.c)'}"
    )
    status = 0
    for kit in args.kits:
        try:
            report = guard(Path(kit), refs, table)
        except GuardError as e:
            print(f"guard: FAILED {kit}: {e}", file=sys.stderr)
            status = 1
            continue
        if report.ok:
            print(f"guard: OK {kit}: {report.files} files, {report.size} bytes")
        else:
            status = 1
            print(f"guard: FAILED {kit}: {len(report.findings)} finding(s)", file=sys.stderr)
            for finding in report.findings:
                print(f"  {finding}", file=sys.stderr)
    return status


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python3 -m mtport.release", description=__doc__.splitlines()[0]
    )
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("guard", help="fail if a kit holds anything derived from the game")
    p.add_argument("kits", nargs="+", metavar="KIT", help=".zip, .tar.gz or directory")
    p.add_argument(
        "--reference",
        action="append",
        default=[],
        metavar="DIR",
        help="also reject files with the SHA-256 of a file below DIR (repeatable)",
    )
    p.add_argument(
        "--no-default-references",
        action="store_true",
        help=f"don't use {', '.join(DEFAULT_REFERENCES)} of this checkout",
    )
    p.add_argument("--dispatch", metavar="FILE", help=f"generated dispatch.c ({GEN_DISPATCH})")
    p = sub.add_parser("tag", help="print the version and release|prerelease of a tag")
    p.add_argument("tag")
    p = sub.add_parser("kits", help="print the expected kit file names of VERSION")
    p.add_argument("version")
    p = sub.add_parser("sha256", help="write FILE.sha256 next to each FILE")
    p.add_argument("files", nargs="+", metavar="FILE")
    p = sub.add_parser("sums", help="merge .sha256 files into OUT")
    p.add_argument("out")
    p.add_argument("files", nargs="+", metavar="FILE.sha256")
    p = sub.add_parser("check", help="check the files next to SUMS (like sha256sum -c)")
    p.add_argument("sums")
    args = parser.parse_args(argv)

    try:
        if args.cmd == "guard":
            return _cmd_guard(args)
        if args.cmd == "tag":
            version, pre = parse_tag(args.tag)
            print(version)
            print("prerelease" if pre else "release")
        elif args.cmd == "kits":
            parse_tag("v" + args.version)
            print("\n".join(kit_names(args.version)))
        elif args.cmd == "sha256":
            for f in args.files:
                print(write_sha256(Path(f)).read_text(encoding="utf-8"), end="")
        elif args.cmd == "sums":
            text = merge_sums(Path(f) for f in args.files)
            Path(args.out).write_bytes(text.encode("utf-8"))
            print(text, end="")
        elif args.cmd == "check":
            failures = check_sums(Path(args.sums))
            for line in failures:
                print(line, file=sys.stderr)
            return 1 if failures else 0
    except (ValueError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2 if args.cmd in ("tag", "kits") else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
