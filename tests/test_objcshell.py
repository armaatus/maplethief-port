"""Unit tests for the ObjC shell inventory (mtport.objcshell) on synthetic inputs.

The real slice, export and doc are checked in test_objcshell_real.py.
"""

from __future__ import annotations

from types import SimpleNamespace

import pytest

from mtport import armscan, names, nib, objc, objcshell

# -- curated names ------------------------------------------------------------------------


def test_curated_names_are_unique_and_legal():
    entries = objcshell.curated_names()
    locations = [fp & ~1 for fp, _, _, _ in entries]
    assert len(locations) == len(set(locations))
    assert all(fp & 1 for fp, _, _, _ in entries)  # all Thumb
    doc = {
        "source": objcshell.SOURCE,
        "names": [
            {"address": f"0x{fp:X}", "name": n, "kind": "function"} for fp, _, n, _ in entries
        ],
    }
    names.parse(doc, "objcshell.json")  # raises on a malformed or reserved name
    # 8 blocks with copy and dispose helpers, 12 bridges.
    assert len(entries) == len(objcshell.SHELL_NAMES) + 24 + len(objcshell.BRIDGES)


def test_build_names_checks_starts_and_other_files():
    starts = {fp for fp, _, _, _ in objcshell.curated_names()}
    image = SimpleNamespace(function_starts=starts)
    entries = objcshell.build_names(image, {})
    assert {e["address"] for e in entries} == {f"0x{fp:X}" for fp in starts}
    bridge = next(e for e in entries if e["name"] == "Shell_EnableMapKey")
    assert bridge["comment"].startswith("engine -> shell bridge")
    with pytest.raises(objcshell.ShellError, match="not an LC_FUNCTION_STARTS"):
        objcshell.build_names(SimpleNamespace(function_starts=starts - {0x55B5}), {})
    with pytest.raises(objcshell.ShellError, match="another names file"):
        objcshell.build_names(image, {0x55B4: "SomethingElse"})
    # The same name from another file is fine.
    objcshell.build_names(image, {0x55B4: "EAGLView_CGPointMake"})


def test_bridge_name():
    assert objcshell.bridge_name("enalbeHelpScrollKey") == "Shell_EnalbeHelpScrollKey"


# -- doc blocks ---------------------------------------------------------------------------


DOC = """# T

<!-- BEGIN generated:a -->
old
<!-- END generated:a -->

text

<!-- BEGIN generated:class:B -->
<!-- END generated:class:B -->
"""


def test_render_replaces_only_block_bodies():
    out = objcshell.render(DOC, {"a": "new\n", "class:B": "b"})
    assert "old" not in out
    assert "<!-- BEGIN generated:a -->\n<!-- Generated by" in out
    assert "new\n<!-- END generated:a -->" in out
    assert "b\n<!-- END generated:class:B -->" in out
    assert "\ntext\n" in out
    assert objcshell.render(out, {"a": "new\n", "class:B": "b"}) == out  # idempotent


@pytest.mark.parametrize(
    ("blocks", "message"),
    [
        ({"a": "x"}, "unknown block class:B"),
        ({"a": "x", "class:B": "y", "c": "z"}, "no block for c"),
    ],
)
def test_render_rejects_mismatched_blocks(blocks, message):
    with pytest.raises(objcshell.ShellError, match=message):
        objcshell.render(DOC, blocks)


def test_render_rejects_duplicate_blocks():
    doc = DOC + "<!-- BEGIN generated:a -->\n<!-- END generated:a -->\n"
    with pytest.raises(objcshell.ShellError, match="appears 2 times"):
        objcshell.render(doc, {"a": "x", "class:B": "y"})


# -- matching and classifying -------------------------------------------------------------


def test_resource_files():
    bundle = ["Default.png", "KeyButton.png", "MainWindow.nib", "a.b.png"]
    assert objcshell.resource_files("KeyButton.png", bundle) == ["KeyButton.png"]
    assert objcshell.resource_files("MainWindow", bundle) == ["MainWindow.nib"]
    assert objcshell.resource_files("a.b", bundle) == ["a.b.png"]
    assert objcshell.resource_files("KeyButton", bundle) == ["KeyButton.png"]
    assert objcshell.resource_files("Missing.png", bundle) == []
    assert objcshell.resource_files("dir/KeyButton.png", bundle) == []
    assert objcshell.resource_files("", bundle) == []


def _method(sel: str, types: str = "v8@0:4") -> objc.Method:
    return objc.Method(sel, types, 0x1001)


def test_argument_words_from_type_strings():
    k = objc.ObjCClass(0, "V", 0, None, 0, 0, 0)
    k.instance_methods = [
        _method("tap:", "v12@0:4@8"),
        _method("add:frame:", "@32@0:4@8{CGRect=ffff}12"),
    ]
    o = objc.ObjCImage([k], [], [], [], [], [], [])
    assert objcshell.argument_words(o) == {"tap:": 1, "add:frame:": 6}


def _send(sel, receiver=None, *, how=None, in_image=None, impl=None, class_method=False):
    return {
        "selector": sel,
        "receiver": receiver,
        "how": how,
        "in_image": in_image,
        "implemented_by": impl,
        "class_method": class_method,
    }


def _info() -> objcshell.Selectors:
    return objcshell.Selectors(
        app={"createGLes": {"GLView"}, "release": {"Singleton"}, "tap:": {"Pad", "Panel"}},
        framework={"release", "setFrame:"},
        strict={"release", "setFrame:"},
        supers={"GLView": ["UIView", "NSObject"], "Singleton": ["NSObject"]},
    )


def test_classify():
    info = _info()
    f, a = objcshell.FRAMEWORK, objcshell.APP
    # Unknown receiver: a framework selector stays framework even if an app class has it.
    assert objcshell.classify(_send("release"), info)[0] == f
    assert objcshell.classify(_send("tap:"), info)[:2] == (a, frozenset({"Pad", "Panel"}))
    assert objcshell.classify(_send("setAlpha:"), info) == (f, frozenset(), "?")
    assert objcshell.classify(_send(None), info)[0] == objcshell.UNKNOWN
    # Resolved receivers.
    kind, owners, _ = objcshell.classify(
        _send("tap:", "Pad", how="alloc", in_image=True, impl="Pad"), info
    )
    assert (kind, owners) == (a, frozenset({"Pad"}))
    assert objcshell.classify(_send("x", "CBThing", in_image=True, impl="CBThing"), info)[0] == (
        objcshell.CHARTBOOST
    )
    # [super initWithCoder:] makes the resolver see UIView for later sends on self.
    sent = _send("createGLes", "UIView", how="init", in_image=False, impl="UIView")
    assert objcshell.classify(sent, info)[:2] == (a, frozenset({"GLView"}))
    # ...but not for a selector that firmly resolved sends use with a framework class.
    sent = _send("release", "UIView", how="init", in_image=False, impl="UIView")
    assert objcshell.classify(sent, info)[0] == f
    sent = _send("setFrame:", "UIImageView", how="alloc", in_image=False, impl="UIImageView")
    assert objcshell.classify(sent, info) == (f, frozenset(), "UIImageView")


def test_argument_selectors():
    selrefs = [(0x100, "addTarget:action:"), (0x104, "tapped:"), (0x108, "other")]
    refs = [
        armscan.Ref(0x10, 0x1, 0x100, "load"),  # selector of the send at 0x20
        armscan.Ref(0x14, 0x1, 0x104, "load"),  # an argument of it
        armscan.Ref(0x30, 0x1, 0x108, "load"),  # selector of a send the scan lost
    ]
    sends = [
        {"function": 0x1, "site": 0x20, "selector": "addTarget:action:"},
        {"function": 0x1, "site": 0x40, "selector": None},
    ]
    p = SimpleNamespace(
        objc=SimpleNamespace(selrefs=selrefs),
        scan=SimpleNamespace(refs=refs),
        sends=sends,
    )
    assert objcshell.argument_selectors(p, {0x1}) == [(0x1, "tapped:", "addTarget:action:")]


def test_keycode():
    assert objcshell._keycode(53) == "53 `'5'`"
    assert objcshell._keycode(0xFFFFFFFB) == "-5"
    assert objcshell._keycode(None) == "?"


# -- the nib block ------------------------------------------------------------------------


def test_nib_block():
    classes = [
        nib.NibClass(n)
        for n in ("NSObject", "NSArray", "NSString", "UIWindow", "UIRuntimeOutletConnection")
    ]
    keys = [
        "UINibConnectionsKey",
        "UINibEncoderEmptyKey",
        "NS.bytes",
        "UILabel",
        "UISource",
        "UIDestination",
        "UIBounds",
        "UIOpaque",
    ]
    v = nib.Value
    objects = [
        nib.NibObject(0, 0, [v("UINibConnectionsKey", nib.OBJECT, nib.Ref(1))]),
        nib.NibObject(1, 1, [v("UINibEncoderEmptyKey", nib.OBJECT, nib.Ref(2))]),
        nib.NibObject(
            2,
            4,
            [
                v("UILabel", nib.OBJECT, nib.Ref(3)),
                v("UISource", nib.OBJECT, nib.Ref(4)),
                v("UIDestination", nib.OBJECT, nib.Ref(4)),
            ],
        ),
        nib.NibObject(3, 2, [v("NS.bytes", nib.DATA, b"window")]),
        nib.NibObject(
            4,
            3,
            [
                v("UIBounds", nib.DATA, b"\x06" + b"\0" * 8 + b"\0\0\xa0\x43\0\0\xf0\x43"),
                v("UIOpaque", nib.FALSE, None),
            ],
        ),
    ]
    archive = nib.NibArchive(1, 9, objects, keys, classes)
    text = objcshell.nib_block(archive)
    assert "5 objects, 8 keys, 8 values, 5 classes" in text
    assert '| 3 | `NSString` | `NSString` | "window" |' in text
    assert "`UIBounds` = (0, 0, 320, 480); `UIOpaque` = NO" in text
    assert "| `UINibConnectionsKey` | #1: #2 `UIRuntimeOutletConnection` |" in text
    assert "| #2 `UIRuntimeOutletConnection` | #4 `UIWindow` | `window` | #4 `UIWindow` |" in text
