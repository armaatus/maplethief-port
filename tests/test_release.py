def test_find_table_strides():
    keys = [a.to_bytes(4, "little") for a in TABLE]
    assert rel.find_table(b"xx" + b"".join(k + b"\0" * 4 for k in keys), TABLE) == 2
    assert rel.find_table(b"".join(k + b"\0" * 12 for k in keys), TABLE) == 0
    assert rel.find_table(b"".join(keys), TABLE) == -1  # 4 bytes apart: not an mt_fn_entry
    assert rel.find_table(b"".join(keys), []) == -1


def test_dispatch_table_addresses(tmp_path):
    rows = "\n".join(f"    {{0x{a:08X}u, f_{a:08X}}}," for a in TABLE + [0x3000])
    path = tmp_path / "dispatch.c"
    path.write_text(
        f'#include "mt_gen.h"\nconst mt_fn_entry mt_fn_table[] = {{\n{rows}\n}};\n',
        encoding="utf-8",
    )
    assert rel.dispatch_table_addresses(path) == TABLE
    assert rel.dispatch_table_addresses(tmp_path / "absent.c") == []


