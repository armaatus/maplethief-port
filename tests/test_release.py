def test_stripped_player_build_passes_by_its_dispatch_table(tmp_path):
    # The Windows player executable keeps no symbol names, only mt_fn_table's data.
    table = b"".join(a.to_bytes(4, "little") + b"\0" * 12 for a in TABLE)
