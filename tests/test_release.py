@pytest.mark.skipif(
    not (shutil.which("sha256sum") or shutil.which("shasum")), reason="no sha256sum or shasum"
)
def test_sums_readable_by_system_tools(tmp_path):
    kit = tmp_path / "MapleThief-kit-1.0.0-windows-x64.zip"
    kit.write_bytes(b"windows kit")
    (tmp_path / "SHA256SUMS").write_text(
        rel.merge_sums([rel.write_sha256(kit)]), encoding="utf-8", newline="\n"
    )
    cmd = ["sha256sum", "-c"] if shutil.which("sha256sum") else ["shasum", "-a", "256", "-c"]
    out = subprocess.run([*cmd, "SHA256SUMS"], cwd=tmp_path, capture_output=True, text=True)
    assert out.returncode == 0, out.stdout + out.stderr
    assert f"{kit.name}: OK" in out.stdout


