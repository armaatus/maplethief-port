def test_sha256_files_and_sums(tmp_path):
    a = tmp_path / "MapleThief-kit-1.0.0-linux-x86_64.tar.gz"
    b = tmp_path / "MapleThief-kit-1.0.0-macos-universal.zip"
    a.write_bytes(b"linux kit")
    b.write_bytes(b"mac kit")
    sa, sb = rel.write_sha256(a), rel.write_sha256(b)
    digest = hashlib.sha256(b"linux kit").hexdigest()
    assert sa.read_bytes() == f"{digest}  {a.name}\n".encode()
    text = rel.merge_sums([sb, sa])
    assert text.splitlines()[0].endswith(a.name)  # sorted by name
    sums = tmp_path / "SHA256SUMS"
    sums.write_text(text, encoding="utf-8", newline="\n")
    assert rel.check_sums(sums) == []
    b.write_bytes(b"tampered")
    assert rel.check_sums(sums) == [f"{b.name}: FAILED"]
    a.unlink()
    assert f"{a.name}: missing" in rel.check_sums(sums)


