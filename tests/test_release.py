def write_dir(root: Path, files: dict[str, bytes]) -> Path:
    for name, data in files.items():
        p = root / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return root


def make_zip(path: Path, files: dict[str, bytes], top: str = TOP) -> Path:
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{top}/", b"")
        for name, data in files.items():
            z.writestr(f"{top}/{name}", data)
    return path


def make_tgz(path: Path, files: dict[str, bytes], top: str = TOP, links=()) -> Path:
    with tarfile.open(path, "w:gz") as t:
        for name, data in files.items():
            info = tarfile.TarInfo(f"{top}/{name}")
            info.size = len(data)
            t.addfile(info, io.BytesIO(data))
        for name, target, kind in links:
            info = tarfile.TarInfo(f"{top}/{name}")
            info.type = tarfile.SYMTYPE if kind == "symlink" else tarfile.LNKTYPE
            info.linkname = target
            t.addfile(info)
    return path


def run_guard(kit: Path, refs=None, table=()) -> rel.Report:
    return rel.guard(kit, refs or {}, list(table))


def rules(report: rel.Report) -> set[tuple[str, str]]:
    return {(f.member.removeprefix(f"{TOP}/"), f.rule) for f in report.findings}


