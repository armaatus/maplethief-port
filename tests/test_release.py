def build_kit(tmp_path: Path, fmt: str, files: dict[str, bytes]) -> Path:
    tmp_path.mkdir(parents=True, exist_ok=True)
    if fmt == "zip":
        return make_zip(tmp_path / f"{TOP}.zip", files)
    if fmt == "tar.gz":
        return make_tgz(tmp_path / f"{TOP}.tar.gz", files)
    return write_dir(tmp_path / TOP, files)


