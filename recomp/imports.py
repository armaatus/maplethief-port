"""Import ids and the generated import table (#36 extends this).

Every import gets a stable id; generated code calls one as ``MT_CALL_IMPORT(id)`` through
``mt_import_table[id]``, which the runtime fills at start-up (calls.h). The #30 prototype
numbers the ``__symbolstub1`` stubs in address order. #36 classifies all 333 imports
(function vs. data), numbers them all, gives every function import a guest code address for
the dispatch table, allocates the data imports' guest objects, and adds the AAPCS
marshalling helpers.
"""

from __future__ import annotations

from dataclasses import dataclass

from recomp.loader import Image


@dataclass(frozen=True)
class ImportTable:
    """``names[id]`` is the import's symbol; ``by_stub`` maps a stub address to its id."""

    names: tuple[str, ...]
    by_stub: dict[int, int]

    @classmethod
    def from_image(cls, image: Image) -> ImportTable:
        stubs = sorted(image.stubs.values(), key=lambda s: s.address)
        return cls(tuple(s.symbol for s in stubs), {s.address: i for i, s in enumerate(stubs)})

    def at(self, addr: int) -> tuple[int, str] | None:
        i = self.by_stub.get(addr & ~1)
        return None if i is None else (i, self.names[i])

    def c_source(self) -> str:
        """``work/gen/imports.c``: the names and the table the runtime fills."""
        lines = [
            "/* Generated by recomp (ADR 0014): import names and the table the runtime fills. */",
            '#include "mt_gen.h"',
            "",
            "const char *const mt_import_names[MT_IMPORT_COUNT] = {",
        ]
        lines += [f'    "{name}", /* {i} */' for i, name in enumerate(self.names)]
        lines += ["};", "", "mt_import_fn mt_import_table[MT_IMPORT_COUNT];", ""]
        return "\n".join(lines)
