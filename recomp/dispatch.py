"""The guest address -> host function table (#35 extends this).

``work/gen/dispatch.c`` lists every generated guest function by its function pointer
(Thumb bit set for Thumb code), sorted, as ``mt_fn_table`` / ``mt_fn_count``; the runtime's
``mt_dispatch`` (calls.h) looks targets up in it. #35 adds the stubs' guest functions, the
fast lookup (dense array over ``__text`` or a perfect hash) and the miss diagnostic.
"""

from __future__ import annotations

from collections.abc import Iterable

from recomp.lift.core import c_name


def c_source(ptrs: Iterable[int]) -> str:
    entries = sorted(set(ptrs))
    lines = [
        "/* Generated by recomp (ADR 0014): guest function pointer -> host function. */",
        '#include "mt_gen.h"',
        "",
        "const mt_fn_entry mt_fn_table[] = {",
    ]
    lines += [f"    {{0x{p:08X}u, {c_name(p)}}}," for p in entries]
    lines += ["};", f"const uint32_t mt_fn_count = {len(entries)}u;", ""]
    return "\n".join(lines)
