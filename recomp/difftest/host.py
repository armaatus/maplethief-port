"""The host side of the differential test: the lifted C, built once and run per function.

:func:`build` lifts every selected function twice, as production code (``f_XXXXXXXX``,
default :class:`~recomp.lift.core.LiftOptions`) and with ``flags_in``/``flags_out``
(``g_XXXXXXXX``: the flags start from and end in ``cpu->cpsr``, so NZCV can be compared),
writes them with the function table ``fns.c`` and compiles them with ``driver.c`` into one
executable, with the strict flags of the tests (ADR 0002: C17, all warnings as errors, FP
contraction off). The host compiler is ``$MAPLETHIEF_CC`` or ``$CC``, else MSVC ``cl`` on
Windows when it is on PATH, else ``clang``, ``cc`` or ``gcc``.

File formats (every field a little-endian uint32; byte strings padded to 4):

- **pristine**: the raw window, :data:`~recomp.difftest.inputs.WINDOW` bytes.
- **cases** (:func:`write_cases`): ``"MTD1"``, function index, window size, heap address,
  heap size, pool count, case count; the pool images; then per case: case id, pool index,
  r0-r15, cpsr, fpscr, d0-d31 (low word first), patch count, then per patch: address,
  length, bytes.
- **results** (:func:`read_results`): ``"MTD2"``, record count; per record (two per case,
  variant 0 = ``f_``, 1 = ``g_``): case id, variant, status (0 return, 1 memory fault,
  2 trap, 3 dispatch miss, 4 SjLj hook), three detail words (fault: address, size, pc;
  trap: kind, pc, detail), r0-r15, cpsr, fpscr, d0-d31, range count, then per range of
  changed bytes: address, length, bytes.
"""

from __future__ import annotations

import os
import shutil
import struct
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

from recomp import REPO
from recomp.difftest.inputs import HEAP, HEAP_SIZE, WINDOW, Case
from recomp.difftest.select import ImageProgram, Leaf
from recomp.lift.core import LiftOptions, c_name, lift_function

DRIVER = Path(__file__).with_name("driver.c")
INCLUDE = REPO / "runtime" / "include"
FLAGS_OPTIONS = LiftOptions(flags_in=True, flags_out=True)
CHUNK = 64  # functions per translation unit
STATUS = ("return", "fault", "trap", "dispatch", "sjlj")


class BuildError(RuntimeError):
    pass


@dataclass(frozen=True)
class Compiler:
    path: str
    msvc: bool

    def compile(self, src: Path, obj: Path) -> list[str]:
        if self.msvc:
            cmd = [self.path, "/nologo", "/std:c17", "/W4", "/WX", "/O1", "/fp:precise", "/utf-8"]
            return cmd + ["/D_CRT_SECURE_NO_WARNINGS", f"/I{INCLUDE}", "/c", str(src), f"/Fo{obj}"]
        cmd = [self.path, "-std=c17", "-Wall", "-Wextra", "-Werror", "-O1", "-ffp-contract=off"]
        return cmd + [f"-I{INCLUDE}", "-c", str(src), "-o", str(obj)]

    def link(self, objs: list[Path], exe: Path) -> list[str]:
        if self.msvc:
            return [self.path, "/nologo", *map(str, objs), f"/Fe{exe}"]
        cmd = [self.path, *map(str, objs), "-o", str(exe)]
        return cmd + (["-lm"] if sys.platform.startswith("linux") else [])


def find_compiler() -> Compiler:
    for env in ("MAPLETHIEF_CC", "CC"):
        if os.environ.get(env):
            path = os.environ[env]
            return Compiler(path, Path(path).name.lower().startswith("cl"))
    if sys.platform == "win32" and shutil.which("cl"):
        return Compiler(shutil.which("cl"), True)
    for name in ("clang", "cc", "gcc"):
        path = shutil.which(name)
        if path:
            return Compiler(path, False)
    raise BuildError("no C compiler found (set MAPLETHIEF_CC)")


def flags_name(ptr: int) -> str:
    return "g" + c_name(ptr)[1:]


def sources(image, leaves: list[Leaf]) -> dict[str, str]:
    """File name -> C source of the lifted functions and ``fns.c``."""
    program = ImageProgram(image, {lf.ptr for lf in leaves})
    decls = []
    bodies = []
    for lf in leaves:
        g = lift_function(lf.fn, program, FLAGS_OPTIONS, name=flags_name(lf.ptr))
        if not g.clean:
            raise BuildError(f"{flags_name(lf.ptr)}: {g.problems or g.unsupported}")
        decls += [f"void {lf.lifted.name}(mt_cpu *MT_RESTRICT cpu);"]
        decls += [f"void {g.name}(mt_cpu *MT_RESTRICT cpu);"]
        bodies.append(lf.lifted.source + "\n" + g.source)
    head = '#include "maplethief/recomp/recomp.h"\n\n' + "\n".join(decls) + "\n\n"
    out = {}
    for i in range(0, len(bodies), CHUNK):
        out[f"lifted_{i // CHUNK:03d}.c"] = head + "\n".join(bodies[i : i + CHUNK])
    rows = [f"    {{0x{lf.ptr:08X}u, {lf.lifted.name}, {flags_name(lf.ptr)}}}," for lf in leaves]
    out["fns.c"] = "\n".join(
        [
            "/* Generated by recomp.difftest.host: the functions under test. */",
            head.rstrip(),
            "typedef struct mt_dt_fn {",
            "    uint32_t ptr;",
            "    mt_guest_fn fn;",
            "    mt_guest_fn flags_fn;",
            "} mt_dt_fn;",
            f"extern const mt_dt_fn mt_dt_fns[{max(len(leaves), 1)}];",
            "extern const uint32_t mt_dt_fn_count;",
            f"const mt_dt_fn mt_dt_fns[{max(len(leaves), 1)}] = {{",
            *(rows or ["    {0u, 0, 0},"]),
            "};",
            f"const uint32_t mt_dt_fn_count = {len(leaves)}u;",
            "",
        ]
    )
    return out


def build(image, leaves: list[Leaf], out_dir: Path, jobs: int = 4) -> Path:
    """Write and compile the executable for ``leaves`` (in this order) into ``out_dir``."""
    cc = find_compiler()
    out_dir.mkdir(parents=True, exist_ok=True)
    srcs = [DRIVER]
    for name, text in sources(image, leaves).items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        srcs.append(path)
    obj_ext = ".obj" if cc.msvc else ".o"
    objs = [out_dir / (s.stem + obj_ext) for s in srcs]

    def run(cmd: list[str]) -> None:
        done = subprocess.run(cmd, capture_output=True, text=True, cwd=out_dir)
        if done.returncode != 0 or (cc.msvc and "warning" in done.stdout):
            raise BuildError(f"{' '.join(cmd)}\n{done.stdout}\n{done.stderr}")

    with ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
        list(pool.map(run, [cc.compile(s, o) for s, o in zip(srcs, objs, strict=True)]))
    exe = out_dir / ("driver.exe" if sys.platform == "win32" else "driver")
    run(cc.link(objs, exe))
    for obj in objs:
        obj.unlink()
    return exe


def write_cases(path: Path, fn_index: int, pool: list[bytes], cases: list[tuple[int, Case]]):
    """The case file for function ``fn_index``: ``cases`` are ``(case id, case)``."""
    parts = [
        struct.pack("<7I", 0x3144544D, fn_index, WINDOW, HEAP, HEAP_SIZE, len(pool), len(cases))
    ]
    parts += pool
    for cid, case in cases:
        d = [w for x in case.d for w in (x & 0xFFFFFFFF, x >> 32)]
        parts.append(
            struct.pack("<2I16I2I64I", cid, case.pool, *case.regs, case.cpsr, case.fpscr, *d)
        )
        parts.append(struct.pack("<I", len(case.patches)))
        for addr, data in case.patches:
            parts.append(struct.pack("<2I", addr, len(data)) + data + bytes(-len(data) % 4))
    path.write_bytes(b"".join(parts))


@dataclass
class Result:
    status: str
    detail: tuple[int, int, int]
    regs: list[int]
    cpsr: int
    fpscr: int
    d: list[int]
    mem: dict[int, int]


def read_results(path: Path) -> dict[tuple[int, int], Result]:
    """``(case id, variant) -> Result`` from a results file."""
    data = path.read_bytes()
    magic, count = struct.unpack_from("<2I", data, 0)
    if magic != 0x3244544D:
        raise ValueError(f"{path}: not a results file")
    off = 8
    out: dict[tuple[int, int], Result] = {}
    fixed = struct.Struct("<6I16I2I64I")
    for _ in range(count):
        v = fixed.unpack_from(data, off)
        off += fixed.size
        (nranges,) = struct.unpack_from("<I", data, off)
        off += 4
        mem: dict[int, int] = {}
        for _ in range(nranges):
            addr, n = struct.unpack_from("<2I", data, off)
            off += 8
            for i, b in enumerate(data[off : off + n]):
                mem[addr + i] = b
            off += n + (-n % 4)
        d = [v[24 + 2 * i] | v[25 + 2 * i] << 32 for i in range(32)]
        out[(v[0], v[1])] = Result(STATUS[v[2]], v[3:6], list(v[6:22]), v[22], v[23], d, mem)
    return out


def run_driver(exe: Path, pristine: Path, cases: Path, results: Path, timeout: float) -> str:
    """Run the driver; returns "" or what went wrong (exit status, timeout)."""
    try:
        done = subprocess.run(
            [str(exe), str(pristine), str(cases), str(results)],
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return f"driver timed out after {timeout:.0f} s"
    if done.returncode != 0:
        return f"driver exited with {done.returncode}: {done.stderr.strip()[-500:]}"
    return ""


