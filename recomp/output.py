"""Writing the generated C: the stable partition into translation units (ADR 0021).

``work/gen/`` (git-ignored, never committed)::

    mt_gen.h      includes maplethief/recomp/recomp.h (CPU state, memory API, calls);
                  MT_IMPORT_COUNT; one prototype per generated function and the dispatch
                  table declarations
    fn_NNN.c      the functions of address cell NNN, ``#include "mt_gen.h"`` first
    imports.c     import names, descriptors, binds and thunks, the table storage (#36)
    dispatch.c    guest function pointer -> host function (#35)
    gen.cmake     the list of sources, read by cmake/GeneratedCode.cmake

**Partition.** The address range of the code (``__text`` for the real image) is cut into
``units`` equal cells, and a function goes into the cell that holds its start address:
``unit = (address - lo) * units // (hi - lo)``. The assignment depends on nothing but the
function's own address, so a change to any function's C, of any size, rewrites exactly one
``fn_NNN.c``, and adding or removing a function touches only its own cell (plus
``mt_gen.h`` and ``dispatch.c``, which list the functions). Functions tile
``__text``, so equal cells hold equal guest code, and the C size follows the guest size.
A cell with no function is not written; ``NNN`` is the cell index, so the names of the
other files do not move.

**Write if changed.** Every file is written only when its bytes differ, so an unchanged
file keeps its timestamp and the build does not recompile it; a ``fn_NNN.c`` left over from
an earlier run with other cells is removed.
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from pathlib import Path

from recomp.dispatch import c_source as dispatch_source
from recomp.imports import ImportTable
from recomp.lift.core import Lifted, c_name

# 64 cells of the 880,956-byte __text: about 13.8 KB of guest code and 0.66 MB of C each.
# Measured on an Apple M4 (10 cores) in ADR 0021: the Release build is bound by the largest
# functions (up to 1.26 MB of C each), not by the number of cells.
DEFAULT_UNITS = 64
MAX_UNITS = 1000  # three digits in fn_NNN.c
UNIT_FILE = re.compile(r"fn_\d{3}\.c")
GEN_CMAKE = "gen.cmake"


def write_if_changed(path: Path, text: str) -> bool:
    """Write ``text`` (UTF-8, LF) unless the file already holds exactly that, so an
    unchanged translation unit keeps its timestamp and is not rebuilt."""
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def unit_name(unit: int) -> str:
    return f"fn_{unit:03d}.c"


def partition(
    ptrs: Iterable[int], units: int = DEFAULT_UNITS, span: tuple[int, int] | None = None
) -> dict[int, list[int]]:
    """Cell index -> the function pointers whose address lies in that cell, in address
    order (only non-empty cells). ``span`` is the ``(lo, hi)`` address range to cut; by
    default the range of the functions' own addresses. Addresses outside ``span`` go to the
    first or last cell."""
    if not 1 <= units <= MAX_UNITS:
        raise ValueError(f"units must be 1..{MAX_UNITS}, not {units}")
    ptrs = sorted(set(ptrs), key=lambda p: (p & ~1, p))
    if not ptrs:
        return {}
    lo, hi = span or (ptrs[0] & ~1, (ptrs[-1] & ~1) + 1)
    if hi <= lo:
        raise ValueError(f"empty span {lo:#x}..{hi:#x}")
    cells: dict[int, list[int]] = {}
    for p in ptrs:
        unit = min(units - 1, max(0, ((p & ~1) - lo) * units // (hi - lo)))
        cells.setdefault(unit, []).append(p)
    return cells


def header(ptrs: Iterable[int], imports: ImportTable) -> str:
    lines = [
        "/* Generated by recomp (ADR 0014). Never edit; never commit. */",
        "#ifndef MT_GEN_H",
        "#define MT_GEN_H",
        "",
        '#include "maplethief/recomp/recomp.h"',
        "",
        f"#define MT_IMPORT_COUNT {len(imports.names)}u",
        "",
        "extern const mt_fn_entry mt_fn_table[];",
        "extern const uint32_t mt_fn_count;",
        "",
    ]
    lines += [f"void {c_name(p)}(mt_cpu *MT_RESTRICT cpu);" for p in sorted(set(ptrs))]
    lines += ["", "#endif /* MT_GEN_H */", ""]
    return "\n".join(lines)


def unit_source(functions: list[Lifted]) -> str:
    return "\n".join(['#include "mt_gen.h"', ""] + [f.source for f in functions])


def gen_cmake(sources: list[str]) -> str:
    """``gen.cmake``: the sources relative to its directory (cmake/GeneratedCode.cmake). It
    changes only when a unit appears or disappears, which re-runs the CMake configure step."""
    lines = [
        "# Generated by recomp (ADR 0021). Never edit; never commit.",
        "# Read by maplethief_add_generated_code() in cmake/GeneratedCode.cmake.",
        "set(MAPLETHIEF_GEN_SOURCES",
        *(f"    {name}" for name in sources),
        ")",
        "",
    ]
    return "\n".join(lines)


def write_program(
    out: Path,
    lifted: list[Lifted],
    imports: ImportTable,
    units: int = DEFAULT_UNITS,
    span: tuple[int, int] | None = None,
) -> list[Path]:
    """Write mt_gen.h, the fn_NNN.c cells, imports.c, dispatch.c and gen.cmake into ``out``
    (each only if it changed); returns the C sources to compile."""
    ptrs = [f.ptr for f in lifted]
    by_ptr = {f.ptr: f for f in lifted}
    cells = partition(ptrs, units, span)
    sources = {unit_name(u): unit_source([by_ptr[p] for p in c]) for u, c in cells.items()}
    write_if_changed(out / "mt_gen.h", header(ptrs, imports))
    sources["imports.c"] = imports.c_source()
    sources["dispatch.c"] = dispatch_source(ptrs)
    for name, text in sources.items():
        write_if_changed(out / name, text)
    for stale in out.glob("fn_*.c"):
        if UNIT_FILE.fullmatch(stale.name) and stale.name not in sources:
            stale.unlink()
    write_if_changed(out / GEN_CMAKE, gen_cmake(list(sources)))
    return [out / name for name in sources]
